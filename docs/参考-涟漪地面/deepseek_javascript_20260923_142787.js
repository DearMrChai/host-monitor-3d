/* ============================================================================
 * 涟漪参数配置
 * ----------------------------------------------------------------------------
 * 这 5 个参数决定了涟漪的全部视觉表现，可以暴露成 UI 滑块让用户实时调节
 * ============================================================================
 */
const PULSE_SETTINGS = {
  
  /* ------------------------------------------------------------------------
   * 涟漪高度（rippleHeight）
   * ------------------------------------------------------------------------
   * 单位：世界单位（米）
   * 范围：建议 0 ~ 8
   * 
   * 效果：
   *   0       → 涟漪只有颜色变化，地面完全平整（水面静谧感）
   *   0.5     → 微弱的起伏，像平静湖面被石子轻触（推荐）
   *   2.5     → 明显的波浪隆起，像水面被投入石块
   *   8       → 剧烈的山丘状波动，有冲击力但会破坏"数据感"
   * 
   * 推荐值：0.5（静谧） / 2.5（标准） / 5（强烈）
   * ------------------------------------------------------------------------ */
  rippleHeight: 0.5,
  
  /* ------------------------------------------------------------------------
   * 涟漪扩散速度（rippleSpeed）
   * ------------------------------------------------------------------------
   * 单位：世界单位 / 秒
   * 范围：建议 5 ~ 50
   * 
   * 效果：
   *   5       → 极慢，涟漪几乎贴地爬行，禅意
   *   10      → 缓慢优雅，像水面涟漪（推荐）
   *   22      → 标准速度，有明显的脉冲节奏
   *   50      → 快速扫过，像冲击波，压迫感强
   * 
   * 推荐值：10（安谧） / 22（标准） / 40（急促）
   * ------------------------------------------------------------------------ */
  rippleSpeed: 10,
  
  /* ------------------------------------------------------------------------
   * 涟漪环厚度（rippleThickness）
   * ------------------------------------------------------------------------
   * 单位：无量纲（相对系数）
   * 范围：建议 0.3 ~ 4
   * 
   * 效果：
   *   0.3     → 极细的一圈，像激光环，锐利清晰
   *   1.0     → 精细的一圈，优雅（推荐）
   *   2.0     → 中等宽度，柔和的涟漪
   *   4.0     → 宽厚的一圈，像水波缓慢荡漾
   * 
   * 推荐值：1.0（锐利） / 2.0（柔和）
   * 
   * 注意：数值过大时涟漪可能互相重叠，失去"环"的形状
   * ------------------------------------------------------------------------ */
  rippleThickness: 1.0,
  
  /* ------------------------------------------------------------------------
   * 涟漪亮度（rippleBrightness）
   * ------------------------------------------------------------------------
   * 单位：无量纲（颜色增益倍数）
   * 范围：建议 0 ~ 2
   * 
   * 效果：
   *   0       → 涟漪完全隐形（只有高度起伏，没有颜色变化）
   *   0.25    → 若隐若现，非常克制（推荐）
   *   1.0     → 标准亮度，涟漪清晰可见
   *   2.0     → 过曝发白，会破坏整体色调
   * 
   * 推荐值：0.25（克制） / 1.0（标准）
   * 
   * 注意：配合辉光（Bloom）效果时，亮度过高会导致涟漪一片白
   * ------------------------------------------------------------------------ */
  rippleBrightness: 0.25,
  
  /* ------------------------------------------------------------------------
   * 数字雨亮度（rainBrightness）
   * ------------------------------------------------------------------------
   * 单位：无量纲（透明度倍数）
   * 范围：建议 0 ~ 0.8
   * 
   * 效果：
   *   0       → 数字雨完全隐藏
   *   0.3     → 若隐若现的远景氛围
   *   0.8     → 数字雨成为视觉主角（推荐）
   * 
   * 推荐值：0.3（涟漪为主） / 0.8（数字雨为主）
   * ------------------------------------------------------------------------ */
  rainBrightness: 0.8
};